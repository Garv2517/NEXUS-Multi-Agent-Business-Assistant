    store_name: str
    store_location: str
    product_id: int
    product_name: str
    category: str
    stock_on_hand: int
    annual_units_sold: int
    average_daily_velocity: float
    days_of_supply: float
    inventory_cost_value_cents: int
    currency_code: str = Field("USD")
    threshold_applied: str
    explanation: str


